def config_root_for(path):
    """The nearest ancestor that owns `_config/` -- a sub-stage or analysis dir's project.

    Walked rather than counted: stage 02 sub-stages sit three levels down and stage 03
    analyses two, and a seam that hard-codes either depth breaks the other.
    """
    here = Path(path).resolve()
    for candidate in [here] + list(here.parents):
        if (candidate / "_config").is_dir():
            return candidate
    return here


