# --- the descriptor ----------------------------------------------------------------------------


def _strip_value(raw):
    """A scalar: quoted span taken whole, otherwise up to an inline ` #` comment.

    Quoted first, deliberately: a Slurm directive line IS a comment (`#SBATCH ...`), so a
    naive comment strip would eat the descriptor's most important content.
    """
    raw = raw.strip()
    if raw[:1] in ('"', "'"):
        quote = raw[0]
        end = raw.find(quote, 1)
        if end != -1:
            return raw[1:end]
        return raw[1:]
    return re.split(r"\s+#", raw, maxsplit=1)[0].strip()


def parse_descriptor(text):
    """The narrow parser for a template we own -- scalars, one-level lists, one-level maps.

    The same trade `wrapperlib.read_config` makes (decision 0011): stdlib-only means no YAML
    library, and the template's shape is fixed and documented in the template itself.
    """
    values = {}
    section = None
    for raw in text.splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$", raw)
        if m:
            key, rest = m.group(1), m.group(2)
            if rest.strip():
                values[key] = _strip_value(rest)
                section = None
            else:
                section = key
                values[key] = None      # shape decided by the first child line
            continue
        m = re.match(r"^\s+-\s+(.*)$", raw)
        if m and section:
            if not isinstance(values.get(section), list):
                values[section] = []
            values[section].append(_strip_value(m.group(1)))
            continue
        m = re.match(r"^\s+([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$", raw)
        if m and section:
            if not isinstance(values.get(section), dict):
                values[section] = {}
            values[section][m.group(1)] = _strip_value(m.group(2))
            continue
    return values


def descriptor_path(config_root):
    return Path(config_root) / "_config" / DESCRIPTOR_NAME


def load(config_root):
    """The descriptor for a project. Absent file -> the built-in Slurm descriptor.

    `config_root` is the directory that owns `_config/` -- the project, in GARS's layout.
    """
    path = descriptor_path(config_root)
    if not path.is_file():
        return dict(SLURM)
    parsed = parse_descriptor(path.read_text(encoding="utf-8"))
    name = parsed.get("name") or "slurm"
    base = dict(BUILTINS.get(name, {"name": name}))
    for key, value in parsed.items():
        if value is not None:
            base[key] = value
    base.setdefault("name", name)
    return base


def validate(descriptor):
    """Problems with a descriptor, in member words. Empty list means usable."""
    problems = []
    name = descriptor.get("name")
    if name not in BUILTINS:
        problems.append('R-075: backend must be the enum slurm|local')
    else:
        for key in ('submit_argv', 'status_argv', 'cancel_argv', 'start_argv', 'job_id_regex', 'status_map', 'submit_note'):
            if key in descriptor and descriptor[key] != BUILTINS[name].get(key):
                problems.append('R-075: %s is fixed by the backend enum' % key)
    for key in ('nextflow_config', 'nextflow_profile'):
        value = descriptor.get(key)
        if value:
            try:
                shell_value(value, key)
            except ValueError as exc:
                problems.append(str(exc))
    # Free-form directive templates would be a second executable language.
    if name in BUILTINS and descriptor.get('directives') != BUILTINS[name]['directives']:
        problems.append('R-075: directives must match the registered backend')
    if not name:
        problems.append("the descriptor has no `name:` line; name the backend "
                        "(slurm, local, or your own)")
    directives = descriptor.get("directives")
    if directives is not None and not isinstance(directives, list):
        problems.append("`directives:` must be a list of `- \"...\"` lines")
    elif isinstance(directives, list):
        for line in directives:
            for field in re.findall(r"\{([A-Za-z_]+)\}", line):
                if field not in HEADER_FIELDS:
                    problems.append("directive line names {%s}, which this system does not "
                                    "supply; available: %s"
                                    % (field, ", ".join("{%s}" % f for f in HEADER_FIELDS)))
    if name not in BUILTINS:
        submit_argv = descriptor.get("submit_argv")
        if not isinstance(submit_argv, list) or not submit_argv:
            problems.append("`submit_argv:` must be a non-empty list; it runs the GENERATED "
                            "script and nothing else")
        elif not any("{script}" in a for a in submit_argv):
            problems.append("`submit_argv:` never names {script}; the generated submit.sh is "
                            "the only thing a descriptor may submit")
        status_argv = descriptor.get("status_argv")
        if not isinstance(status_argv, list) or not status_argv:
            problems.append("`status_argv:` must be a non-empty list naming {job_id}")
        elif not any("{job_id}" in a for a in status_argv):
            problems.append("`status_argv:` never names {job_id}")
        if not descriptor.get("job_id_regex"):
            problems.append("`job_id_regex:` is required: it is how the submit output "
                            "becomes a job id")
        else:
            try:
                re.compile(descriptor["job_id_regex"])
            except re.error as exc:
                problems.append("`job_id_regex:` does not compile (%s) -- remember the "
                                "parser takes a quoted value verbatim, with no escape "
                                "processing; a regex needing a double quote must be "
                                "single-quoted" % exc)
        status_map = descriptor.get("status_map")
        if not isinstance(status_map, dict) or not status_map:
            problems.append("`status_map:` must map this backend's states onto %s"
                            % "|".join(STATES))
        else:
            unknown = sorted({v for v in status_map.values() if v not in STATES})
            if unknown:
                problems.append("`status_map:` maps onto %s, which are not in the closed "
                                "vocabulary %s" % (", ".join(unknown), "|".join(STATES)))
    return problems


# --- the three doors ---------------------------------------------------------------------------


def _fill(text, fields):
    """Substitute the KNOWN {tokens} and leave every other brace alone.

    Deliberately not str.format: a descriptor element may legitimately contain literal
    braces -- the awsbatch submit argv carries a JSON --container-overrides payload, and
    format() reads {"command": ...} as a placeholder named \'"command"\' and crashes. The
    descriptor is data, not a template language; only the documented tokens are tokens.
    """
    for key, value in fields.items():
        text = text.replace("{%s}" % key, str(value))
    return text


def header_lines(config_root, cfg, project, assay, substage, descriptor=None):
    """The directives block, rendered. Returns a list of lines with no trailing newlines."""
    descriptor = descriptor if descriptor is not None else load(config_root)
    fields = {
        "project": project,
        "assay": assay,
        "substage": str(Path(substage).resolve()),
        "partition": cfg.get("compute.partition", "{partition}"),
        "time": cfg.get("compute.time", "{time}"),
        "cpus": cfg.get("compute.cpus", "{cpus}"),
        "mem": cfg.get("compute.mem", "{mem}"),
    }
    problems = validate(descriptor)
    if problems:
        raise ValueError('; '.join(problems))
    fields = {key: (value if key in ('partition', 'time', 'cpus', 'mem')
                          and 'compute.' + key not in cfg
                          else shell_value(value, key)) for key, value in fields.items()}
    return [_fill(line, fields) for line in descriptor.get("directives") or []]


