class ClaimEnvironmentTests(unittest.TestCase):
    def probe_case(self, ci, explicit, expected):
        def unavailable(cls):
            cls.probe = ('GARS_TEST_NO_CONTAINER=1' if explicit else 'docker info: exit 1')
        cleanup = mock.Mock()
        with mock.patch.dict(os.environ, {'CI': ci, 'GARS_TEST_NO_CONTAINER': explicit}), \
                mock.patch.object(row5.Row05DatabaseTests, 'setUpClass', classmethod(unavailable)), \
                mock.patch.object(row5.Row05DatabaseTests, 'tearDownClass', classmethod(lambda cls: cleanup())):
            with self.assertRaisesRegex(expected, 'GARS_TEST_NO_CONTAINER=1' if explicit else 'docker info'):
                ClaimConstraintTests.setUpClass()
            cleanup.assert_called_once()

    def test_explicit_no_container_precedes_ci(self):
        self.probe_case('true', '1', unittest.SkipTest)

    def test_runtime_failure_fails_ci(self):
        self.probe_case('true', '', AssertionError)

    def test_runtime_failure_skips_outside_ci(self):
        self.probe_case('', '', unittest.SkipTest)


