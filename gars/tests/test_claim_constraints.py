@row5.needs_scratch
class ClaimConstraintTests(unittest.TestCase):
    # Reuse row 5's container startup, scratch password, loopback readiness and teardown.
    compose = classmethod(row5.Row05DatabaseTests.compose.__func__)

    @classmethod
    def setUpClass(cls):
        row5.Row05DatabaseTests.setUpClass.__func__(cls)
        if cls.probe:
            probe = cls.probe
            row5.Row05DatabaseTests.tearDownClass.__func__(cls)
            if (os.environ.get('GARS_TEST_NO_CONTAINER') != '1' and
                    os.environ.get('CI', '').lower() in ('1', 'true', 'yes')):
                raise AssertionError('required container probe failed: ' + probe)
            raise unittest.SkipTest('container probe: ' + probe)

    @classmethod
    def tearDownClass(cls):
        row5.Row05DatabaseTests.tearDownClass.__func__(cls)

    def client(self, writer=False, db='source', transaction=False):
        user = 'gars_claims_writer' if writer else self.env['PGUSER']
        argv = self.command + ['exec', '-T', 'db', 'sh', '-c',
            'export PGPASSWORD="$(cat /run/secrets/pg_password)"; '
            'export PGCONNECT_TIMEOUT=5; exec "$@"', 'row07-test',
            'psql', '-h', self.env['PGHOST'], '-p', self.env['PGPORT'], '-U', user,
            '-d', db, '-X', '-A', '-t', '-v', 'ON_ERROR_STOP=1', '-v', 'VERBOSITY=verbose']
        if transaction:
            argv += ['-1']
        # stdin / -f is required for psql -1 to wrap the whole schema.
        argv += ['-f', '-']
        return argv

    def sql(self, query, writer=False, db='source', transaction=False):
        argv = self.client(writer, db, transaction)
        if writer:
            query = """DO $$ BEGIN
                IF current_user <> 'gars_claims_writer' OR
                   (SELECT rolsuper FROM pg_roles WHERE rolname = current_user) THEN
                    RAISE EXCEPTION 'attack principal is not the restricted writer';
                END IF;
                RAISE NOTICE 'writer identity verified';
            END $$;
            """ + query
        return subprocess.run(argv, input=query, env=row5.scrubbed_env(self.env),
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              universal_newlines=True, timeout=60)

    def ok(self, query, **kwargs):
        p = self.sql(query, **kwargs)
        self.assertEqual(p.returncode, 0, p.stderr)
        return p.stdout

    def setUp(self):
        self.ok('DROP DATABASE IF EXISTS source;', db='postgres')
        self.ok('CREATE DATABASE source;', db='postgres')
        self.ok(SCHEMA, transaction=True)
        # The only password value is generated by row 5 in scratch; never a source literal.
        password = self.password.read_text()
        self.assertIsNotNone(re.fullmatch(r'[0-9a-f]{32}', password), 'scratch password must be generated UUID hex')
        self.ok("ALTER ROLE gars_claims_writer PASSWORD '%s';" % password)
        self.ok((FIXTURE / 'fixture.sql').read_text(), transaction=True)

    def orphan_count(self):
        value = self.ok("SELECT count(*) FILTER (WHERE NOT EXISTS (SELECT FROM claims.claim_evidence ce "
                        "WHERE ce.claim_id = c.id)) || '/' || count(*) FROM claims.claim c;").strip()
        orphan, total = map(int, value.split('/'))
        self.assertEqual(orphan, 0)
        self.assertGreater(total, 0)
        print('orphan claims: ' + value, flush=True)

    def attack(self, query, reason, writer=True):
        if not writer:
            query = "SET ROLE gars_claims_owner; " + query
        p = self.sql(query, writer=writer)
        if writer:
            self.assertIn('writer identity verified', p.stderr)
        self.assertNotEqual(p.returncode, 0, 'attack committed: ' + query)
        self.assertIn(reason, p.stderr, 'refused for the wrong reason: ' + p.stderr)
        self.orphan_count()

    def test_direct_writes_and_privilege_escalation(self):
        attacks = [
            "INSERT INTO claims.claim VALUES (99,1,'OBSERVATION','x','{}','{}','r','w');",
            "INSERT INTO claims.run VALUES (99,'q','p','h',false);",
            'UPDATE claims.run SET exploratory=false;',
            'DELETE FROM claims.evidence WHERE id=1;',
            'TRUNCATE claims.claim_evidence;',
            'TRUNCATE claims.claim, claims.claim_evidence;',
            'ALTER TABLE claims.claim DISABLE TRIGGER ALL;',
            'DROP TRIGGER claim_has_evidence ON claims.claim;',
            'SET session_replication_role=replica;',
            'SET ROLE gars_claims_owner;',
            'DELETE FROM claims.claim;',
        ]
        for query in attacks:
            with self.subTest(query=query):
                self.attack(query, '42501')

    def test_empty_evidence_insert(self):
        for ids in ('ARRAY[]::bigint[]', 'NULL'):
            self.attack(insert(evidence=ids), 'requires at least one evidence link')

    def test_deferred_insert_and_owner_whole_claim_deletion(self):
        self.attack("BEGIN; INSERT INTO claims.claim VALUES (99,1,'OBSERVATION','x','{}','{}','r','w'); COMMIT;",
                    'requires at least one evidence link', writer=False)
        # An immediate-only INSERT trigger would refuse this legitimate transaction.
        self.ok("BEGIN; INSERT INTO claims.claim VALUES (99,1,'OBSERVATION','x','{}','{}','r','w');"
                'INSERT INTO claims.claim_evidence VALUES (99,1); COMMIT;')
        self.ok('BEGIN; DELETE FROM claims.claim_evidence WHERE claim_id=99; '
                'DELETE FROM claims.claim WHERE id=99; COMMIT;')
        self.orphan_count()

    def test_delete_links_same_and_later_transactions(self):
        self.attack('BEGIN; ' + insert() + ' DELETE FROM claims.claim_evidence WHERE claim_id=99; COMMIT;',
                    'requires at least one evidence link')
        self.ok(insert(), writer=True)
        self.attack('BEGIN; DELETE FROM claims.claim_evidence WHERE claim_id=99; COMMIT;',
                    'requires at least one evidence link')
        # Removing one of two links is legitimate; removing the last one later is not.
        self.ok('DELETE FROM claims.claim_evidence WHERE claim_id=1 AND evidence_id=3;', writer=True)
        self.attack('DELETE FROM claims.claim_evidence WHERE claim_id=1;',
                    'requires at least one evidence link')

    def test_update_links_checks_old_and_new(self):
        self.attack('UPDATE claims.claim_evidence SET claim_id=1 WHERE claim_id=3;',
                    'requires at least one evidence link')
        self.ok('UPDATE claims.claim_evidence SET evidence_id=2 WHERE claim_id=2;', writer=True)
        self.attack('UPDATE claims.claim_evidence SET evidence_id=999 WHERE claim_id=2;', '23503')
        self.attack('UPDATE claims.claim_evidence SET claim_id=999 WHERE claim_id=2;', '23503')
        self.orphan_count()

    def test_set_constraints_games(self):
        for mode in ('IMMEDIATE', 'DEFERRED'):
            self.attack('BEGIN; SET CONSTRAINTS ALL ' + mode + '; '
                        'DELETE FROM claims.claim_evidence WHERE claim_id=3; COMMIT;',
                        'requires at least one evidence link')
        self.attack('BEGIN; DELETE FROM claims.claim_evidence WHERE claim_id=3; '
                    'SET CONSTRAINTS ALL IMMEDIATE; COMMIT;', 'requires at least one evidence link')
        self.attack('BEGIN; SET CONSTRAINTS ALL IMMEDIATE; ' + insert() +
                    ' DELETE FROM claims.claim_evidence WHERE claim_id=99; COMMIT;',
                    'requires at least one evidence link')

    def test_evidence_exactly_one_and_enums(self):
        for parents in ('NULL,NULL', '1,1'):
            self.attack("INSERT INTO claims.evidence VALUES (99,%s,'computational','supports');" % parents,
                        '23514')
        self.attack("INSERT INTO claims.evidence VALUES (99,1,NULL,'invalid','supports');", '23514')
        self.attack("INSERT INTO claims.evidence VALUES (99,1,NULL,'computational','invalid');", '23514')
        self.attack(insert().replace("'OBSERVATION'", "'INVALID'"), '23514')

    def test_fk_restrict_as_owner(self):
        self.attack('DELETE FROM claims.evidence WHERE id=1;', '23503', writer=False)
        self.attack('DELETE FROM claims.claim WHERE id=1;', '23503', writer=False)
        self.attack(insert(evidence='ARRAY[999]::bigint[]'), '23503')
        self.attack(insert(rid=999), '23503')

    def test_confidence_groups(self):
        for value in ("'null'", "'1'", "'[]'", "'\"high\"'", "'{\"confidence\":1}'",
                      "'{\"score\":1}'", "'{\"unexpected\":1}'"):
            for group in ('bio', 'risk'):
                with self.subTest(group=group, value=value):
                    self.attack(insert(**{group: value}), '23514')
        for group, key in (('bio', 'replication'), ('risk', 'data_quality')):
            for nested in ('{"confidence":1}', '[{"score":1}]'):
                self.attack(insert(**{group: "'{\"%s\":%s}'" % (key, nested)}), '23514')
        self.ok(insert(bio="'{\"replication\":{\"count\":2}}'"), writer=True)
        self.orphan_count()

    def test_owner_registration_writer_claim_positive_control(self):
        functions = self.ok("SELECT p.proname, r.rolname, p.prosecdef, "
                            "array_to_string(p.proconfig, ';') FROM pg_proc p "
                            "JOIN pg_roles r ON r.oid=p.proowner "
                            "WHERE p.pronamespace='claims'::regnamespace "
                            "AND p.proname IN ('run_register','run_register_eligible') "
                            "ORDER BY p.proname;")
        self.assertEqual(functions.strip().splitlines(), [
            'run_register|gars_claims_owner|t|search_path=claims, pg_temp',
            'run_register_eligible|gars_claims_owner|t|search_path=claims, pg_temp'])
        registered = self.ok("SET ROLE gars_claims_owner; "
                             "SELECT claims.run_register_eligible(2,'q','p','h');")
        self.assertEqual(registered.strip().splitlines()[-1], '2')
        self.assertEqual(self.ok('SELECT exploratory FROM claims.run WHERE id=2;').strip(), 'f')
        self.assertEqual(self.ok(insert(rid=2), writer=True).strip().splitlines()[-1], '99')
        self.assertEqual(self.ok('SELECT run_id FROM claims.claim WHERE id=99;').strip(), '2')
        self.assertEqual(self.ok('SELECT evidence_id FROM claims.claim_evidence '
                                 'WHERE claim_id=99;').strip(), '1')
