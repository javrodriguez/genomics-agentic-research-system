# Claude Code's hooks page (Matcher patterns, read on the build day, 20 Nov 2026): a matcher of
# only letters, digits, `_`, `-`, spaces, `,` and `|` is an exact name or a list of exact names
# separated by `|` or `,` with optional whitespace; anything else is an unanchored JavaScript
# regular expression; "*", "" or an omitted matcher matches every name.
EXACT = re.compile(r'[A-Za-z0-9_ ,|-]*\Z')


def matcher_reaches(matcher, name):
    if matcher is None or matcher in ('', '*'):
        return True
    if EXACT.match(matcher):
        return name in [part.strip() for part in re.split(r'[|,]', matcher)]
    return re.search(matcher, name) is not None


def hook(payload):
    return run([sys.executable, HOOK], GARS, payload, {'CLAUDE_PROJECT_DIR': str(GARS)})


def call(tool, data):
    return hook(json.dumps({'tool_name': tool, 'tool_input': data, 'cwd': str(GARS)}))


def judged_names():
    return ('Read', 'Glob', 'Grep') + tuple(guard_hook.WRITE_TOOLS) + ('Bash',)


def pass_names():
    return tuple(getattr(guard_hook, 'PASS_TOOLS', ()))


TALLY = {'refused': set(), 'passed': set(), 'judged': set()}


class EveryToolNameTests(unittest.TestCase):
    @classmethod
    def tearDownClass(cls):
        print('tool names: %d refused, %d passed, %d judged'
              % (len(TALLY['refused']), len(TALLY['passed']), len(TALLY['judged'])))

    def test_the_matcher_reaches_every_name(self):
        settings = json.loads(SETTINGS.read_text())
        groups = [group for group in settings['hooks']['PreToolUse']
                  if any('_system/guard_hook.py' in h.get('command', '')
                         for h in group.get('hooks', []))]
        self.assertTrue(groups)
        for name in UNJUDGED + judged_names() + tuple(PASS_INPUTS):
            with self.subTest(tool=name):
                self.assertTrue(any(matcher_reaches(g.get('matcher'), name) for g in groups),
                                'the guard is never called for %r' % name)

    def test_the_matcher_rule_reading(self):
        # The rule above, on the shapes the hooks page itself gives.
        self.assertTrue(matcher_reaches('Edit|Write', 'Write'))
        self.assertTrue(matcher_reaches('Edit, Write', 'Write'))
        self.assertFalse(matcher_reaches('Edit|Write', 'NotebookEdit'))
        self.assertTrue(matcher_reaches('Edit.*', 'NotebookEdit'))
        self.assertTrue(matcher_reaches('mcp__memory__.*', 'mcp__memory__create'))
        self.assertTrue(matcher_reaches('*', 'Anything'))
        self.assertTrue(matcher_reaches(None, 'Anything'))
        self.assertFalse(matcher_reaches('Edit|Write|MultiEdit|NotebookEdit|Bash|Read|Glob|Grep',
                                         'mcp__filesystem__write_file'))

    def test_unjudged_names_are_refused(self):
        for name in UNJUDGED:
            for label, data in SHAPES:
                with self.subTest(tool=name, shape=label):
                    result = call(name, data)
                    err = result.stderr.decode()
                    self.assertEqual(result.returncode, 2, err)
                    self.assertTrue(err.startswith('Blocked: the guard cannot judge tool '), err)
                    self.assertIn('cannot judge', err)
                    self.assertEqual(err.count('Next:'), 1, err)
                    self.assertIn(re.sub(r'[^A-Za-z0-9_.:-]', '?', name), err)
                    TALLY['refused'].add(name)

    def test_pass_names_are_allowed(self):
        self.assertEqual(sorted(pass_names()), sorted(PASS_INPUTS))
        for name, data in PASS_INPUTS.items():
            with self.subTest(tool=name):
                result = call(name, data)
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertEqual(result.stderr, b'')
                TALLY['passed'].add(name)

    def test_unreadable_tool_name_is_refused(self):
        base = {'tool_input': {'file_path': 'projects/p/x.txt'}, 'cwd': str(GARS)}
        for label, value in (('missing', None), ('empty', ''), ('null', 'null'), ('int', 5),
                             ('list', ['Read']), ('dict', {'name': 'Read'}), ('false', False)):
            with self.subTest(tool_name=label):
                payload = dict(base)
                if label != 'missing':
                    payload['tool_name'] = None if label == 'null' else value
                result = hook(json.dumps(payload))
                self.assertEqual(result.returncode, 2, result.stderr)
                self.assertIn(b'could not read this tool call', result.stderr)

    def test_judged_names_keep_their_arms(self):
        self.assertEqual(len(CONTROLS), 5)
        for tool, data, message in CONTROLS:
            with self.subTest(tool=tool, data=data):
                result = call(tool, data)
                self.assertEqual(result.returncode, 2, result.stderr)
                self.assertEqual(result.stderr.decode(), message.replace('{root}', str(GARS)))
                TALLY['judged'].add(tool)
        for tool, data in (('Read', {'file_path': '_system/guard_hook.py'}),
                           ('Glob', {'pattern': '*.md'}),
                           ('Grep', {'pattern': 'x', 'path': '_references'}),
                           ('Edit', {'file_path': 'projects/p/00_data/rnaseq_bulk/samples.csv',
                                     'old_string': 'a', 'new_string': 'b'}),
                           ('MultiEdit', {'file_path': 'projects/p/notes.md', 'edits': []}),
                           ('NotebookEdit', {'notebook_path': 'projects/p/a.ipynb',
                                             'new_source': 'x'}),
                           ('Bash', {'command': 'python3 _system/stage00_register.py assays'})):
            with self.subTest(tool=tool, allowed=True):
                result = call(tool, data)
                self.assertEqual(result.returncode, 0, result.stderr)
                TALLY['judged'].add(tool)

    def test_the_sets_are_closed_and_exact(self):
        judged = getattr(guard_hook, 'JUDGED_TOOLS', None)
        passed = getattr(guard_hook, 'PASS_TOOLS', None)
        for value in (judged, passed):
            self.assertIsInstance(value, tuple)
            self.assertTrue(value)
            for name in value:
                self.assertIsInstance(name, str)
                self.assertTrue(name)
                self.assertRegex(name, r'\A[A-Za-z]+\Z')
            self.assertEqual(len(set(value)), len(value))
        self.assertFalse(set(judged) & set(passed))
        self.assertEqual(set(judged), set(judged_names()))
        self.assertEqual(len(judged), 8)
        self.assertFalse(set(UNJUDGED) & (set(judged) | set(passed)))

    def test_settings_belts(self):
        settings = json.loads(SETTINGS.read_text())
        self.assertIn('mcp__*', settings['permissions']['deny'])
        self.assertIs(settings.get('disableClaudeAiConnectors'), True)

    def test_both_arms_refuse_the_unknown_grid(self):
        # Parity with the Codex arm, which was already default deny (decision 0266); its code
        # is not changed here.
        for name in UNJUDGED:
            with self.subTest(tool=name):
                payload = json.dumps({'session_id': 's', 'turn_id': 't', 'cwd': str(GARS),
                                      'hook_event_name': 'PreToolUse', 'tool_name': name,
                                      'tool_input': {'path': NOWHERE}, 'tool_use_id': 'c'})
                codex = run([sys.executable, ADAPTER, 'pre-tool-use'], GARS, payload,
                            {'CLAUDE_PROJECT_DIR': str(GARS)})
                claude = call(name, {'path': NOWHERE})
                self.assertEqual(codex.returncode, 2, codex.stderr)
                self.assertIn(b'Next:', codex.stderr)
                self.assertEqual(claude.returncode, 2, claude.stderr)


if __name__ == '__main__':
    unittest.main()
