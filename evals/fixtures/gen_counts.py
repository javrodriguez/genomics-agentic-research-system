#!/usr/bin/env python3
"""Build the counts fixture pair for the `planted-effect` task, with its ground truth.

Two halves, from one generator, differing in exactly one thing:

  positive  --planted 200   200 of 2000 genes carry a real, documented effect
  control   --planted 0     no gene carries any effect; every rejection is a false positive

The control is the half that does the work. A detector that always reports an effect passes the
positive trivially; only the null half can catch it. That is why the pre-freeze pilot requires
the null to produce ZERO rejections through the real DE path before anything is frozen -- if
the fixture itself yields false positives, a later failure could not be attributed to the agent.

THE DATA IS SYNTHETIC AND IS LABELLED SYNTHETIC EVERYWHERE. No nf-core alignment runs; this is a
counts matrix, generated. It is honest miniaturisation of the analysis step, not a pretend
sequencing run, and the published table says so.

Determinism: numpy's default_rng with a fixed seed, at the numpy version pinned in
evals/requirements-planted-effect.txt. The pin is what makes the seed meaningful.

Serves task `planted-effect` in evals/prereg.json.

Usage:
    python gen_counts.py --planted 200 --seed 20260905 --out <dir>
    python gen_counts.py --planted 0   --seed 20260905 --out <dir>
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

N_GENES = 2000
N_PER_GROUP = 6
GROUPS = ("control", "treated")

# Baseline expression is drawn log-uniform so the matrix spans the dynamic range a real
# experiment has: a few hundred well-expressed genes, a long tail of low counts where nothing is
# detectable. A flat baseline would make every planted gene equally easy and the task hollow.
LOG10_MEAN_MIN, LOG10_MEAN_MAX = 0.7, 3.3

# Negative-binomial dispersion. Fixed, not drawn, so the null half's false-positive rate is a
# property of the design rather than of one lucky draw.
DISPERSION = 0.15

# Planted effect, in log2 fold change. Half up, half down, so a grader cannot pass by assuming a
# direction. Chosen to sit above the detection floor for well-expressed genes without being so
# large that the task is trivial -- the pilot measures the recovery it actually produces.
LOG2_FC = 1.6


def negative_binomial(rng, mean: np.ndarray, dispersion: float) -> np.ndarray:
    """NB draws parameterised by mean and dispersion, the way count data is usually modelled.

    variance = mean + dispersion * mean^2. numpy takes (n, p), so convert.
    """
    n = 1.0 / dispersion
    p = n / (n + mean)
    return rng.negative_binomial(n, p)


def build(seed: int, n_planted: int):
    rng = np.random.default_rng(seed)

    gene_ids = [f"GENE{i:05d}" for i in range(N_GENES)]
    sample_ids = [f"{g[:4].upper()}{i + 1}" for g in GROUPS for i in range(N_PER_GROUP)]
    conditions = [g for g in GROUPS for _ in range(N_PER_GROUP)]

    base_mean = 10 ** rng.uniform(LOG10_MEAN_MIN, LOG10_MEAN_MAX, size=N_GENES)

    # Which genes carry an effect, and in which direction. Drawn from the SAME rng before any
    # count is generated, so the truth is fixed by the seed and cannot be chosen after a result.
    planted_idx = np.sort(rng.choice(N_GENES, size=n_planted, replace=False)) if n_planted else np.array([], dtype=int)
    direction = np.zeros(N_GENES)
    if n_planted:
        signs = np.array([1.0, -1.0] * ((n_planted + 1) // 2))[:n_planted]
        rng.shuffle(signs)
        direction[planted_idx] = signs

    counts = np.zeros((N_GENES, len(sample_ids)), dtype=np.int64)
    for j, cond in enumerate(conditions):
        fold = np.ones(N_GENES)
        if cond == "treated" and n_planted:
            fold = 2.0 ** (direction * LOG2_FC)
        counts[:, j] = negative_binomial(rng, base_mean * fold, DISPERSION)

    truth = {
        "seed": seed,
        "n_genes": N_GENES,
        "n_samples": len(sample_ids),
        "n_planted": int(n_planted),
        "log2_fold_change": LOG2_FC if n_planted else 0.0,
        "dispersion": DISPERSION,
        "synthetic": True,
        "note": ("Synthetic counts. No sequencing and no alignment was performed. "
                 "Generated by evals/fixtures/gen_counts.py at the pinned numpy version."),
        "planted_genes": [gene_ids[i] for i in planted_idx],
        "planted_direction": {gene_ids[i]: ("up" if direction[i] > 0 else "down")
                              for i in planted_idx},
    }
    return gene_ids, sample_ids, conditions, counts, truth


def write(out: Path, gene_ids, sample_ids, conditions, counts, truth) -> dict[str, str]:
    out.mkdir(parents=True, exist_ok=True)

    counts_path = out / "counts.csv"
    with counts_path.open("w", newline="\n") as fh:
        fh.write("gene_id," + ",".join(sample_ids) + "\n")
        for i, gid in enumerate(gene_ids):
            fh.write(gid + "," + ",".join(str(int(v)) for v in counts[i]) + "\n")

    design_path = out / "design.csv"
    with design_path.open("w", newline="\n") as fh:
        fh.write("sample_id,condition\n")
        for sid, cond in zip(sample_ids, conditions):
            fh.write(f"{sid},{cond}\n")

    truth_path = out / "truth_planted.json"
    truth_path.write_text(json.dumps(truth, indent=2) + "\n")

    return {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
            for p in (counts_path, design_path, truth_path)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--planted", type=int, required=True, help="200 for the positive half, 0 for the null control")
    ap.add_argument("--seed", type=int, default=20260905)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    gene_ids, sample_ids, conditions, counts, truth = build(args.seed, args.planted)
    digests = write(Path(args.out), gene_ids, sample_ids, conditions, counts, truth)

    print(json.dumps({
        "half": "positive" if args.planted else "control (null)",
        "seed": args.seed,
        "genes": len(gene_ids),
        "samples": len(sample_ids),
        "planted": args.planted,
        "log2_fold_change": truth["log2_fold_change"],
        "synthetic": True,
        "sha256": digests,
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
