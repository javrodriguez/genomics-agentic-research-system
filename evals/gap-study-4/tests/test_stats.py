"""stats.py: every statistical table round 4's reporting rules name, driven by synthetic take records only.

No result exists yet and none is made up here: every record below is generated by the builders in this file
from a stated pattern (a constant reply, a model right on every try, a fixed list of right and wrong tries),
never typed as a table. Each check is also run against an in-memory mutation of what it guards, through the
module's own accessor, and the test asserts the check's result flips (interface 3).

The drift test reads lane E1's original `evals/gap-study-intervals/intervals.py` with `git show 68ec902f:...`
into a temporary module and drives it beside stats' bounds on every (x, n) with n up to 20. It needs the git
history: in a shallow clone or outside git it fails loudly, never skips.
"""

