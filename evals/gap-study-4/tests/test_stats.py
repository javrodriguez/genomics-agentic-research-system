sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent.parent
REPO = HERE.parent.parent
sys.path.insert(0, str(HERE))

import stats  # noqa: E402

SHARED_COMMIT = "68ec902f63bfbe4a18d07e0f564847531898ff95"
ORIGINAL = "evals/gap-study-intervals/intervals.py"

# Synthetic harness and model names: never a real harness's name (only the seam modules type one).
HX, HY, HZ = "harness-x", "harness-y", "harness-z"


def agent(harness=HX):
    return {"harness": harness, "version": "0.0.1-synthetic"}


VIEWS_RIGHT = {"failures": "right", "excluded": "right", "raw": "right"}
VIEWS_WRONG = {"failures": "wrong", "excluded": "wrong", "raw": "wrong"}
VIEWS_STOP = {"failures": "wrong", "excluded": "out", "raw": "stop"}


def rec(**kw):
    """One synthetic graded take record; keyword arguments override the defaults."""
    r = {"arm": "A", "task": "t1", "half": "trap", "model": "m1", "agent": agent(),
         "wording": "w1", "repeat": 1, "pressure": None, "route": "graded", "cell_state": None,
         "label": "right-move", "views": dict(VIEWS_RIGHT)}
    r.update(kw)
    return r


def outcome(word, half="trap", **kw):
    """A record whose standing is `word`: right, wrong, stop (a reserved label), aborted or harness-error."""
    if word == "right":
        return rec(half=half, label="right-move", views=dict(VIEWS_RIGHT), **kw)
    if word == "wrong":
        return rec(half=half, label="wrong-move", views=dict(VIEWS_WRONG), **kw)
    if word == "stop":
        return rec(half=half, label="did-not-reach", views=dict(VIEWS_STOP), **kw)
    if word == "aborted":
        return rec(half=half, label="aborted", route="aborted", views=dict(VIEWS_STOP), **kw)
    if word == "harness-error":
        return rec(half=half, label="harness-error", route="harness-error", views=None, **kw)
    raise ValueError(word)


WORDINGS = ("w1", "w2", "w3", "w4", "w5")
REPEATS = (1, 2)


def cell(pattern_trap, pattern_normal, *, task="t1", model="m1", harness=HX, arm="A"):
    """Records for one (arm, task, model, harness): one trap and one normal record per (wording, repeat), the
    standing of the k-th slot read from each pattern (a list of words, or one word for every slot)."""
    slots = list(itertools.product(WORDINGS, REPEATS))
    out = []
    for half, pattern in (("trap", pattern_trap), ("normal", pattern_normal)):
        words = [pattern] * len(slots) if isinstance(pattern, str) else list(pattern)
        assert len(words) == len(slots)
        for (wording, repeat), word in zip(slots, words):
            if word is None:
                continue
            out.append(outcome(word, half=half, task=task, model=model, agent=agent(harness), arm=arm,
                               wording=wording, repeat=repeat))
    return out


def design(tasks=("t1", "t2", "t3"), **kw):
    d = {"tasks_that_run": list(tasks),
         "harness_models": {HX: ["m1", "m2", "m3"], HY: ["y1", "y2"], HZ: ["z1", "z2"]},
         "stronger_weaker": {HX: ["m1", "m3"], HY: ["y1", "y2"], HZ: ["z1", "z2"]},
         "cross_vendor": ["m1", "y1", "z1"],
         "alpha": "0.05",
         "bootstrap": {"seed": 7, "reps": 200},
         "power": {"seed": 11, "sims": 20, "bootstrap_reps": 40, "wordings": 5, "repeats": 2,
                   "grid": [{"stronger": "0.900", "weaker": "0.500", "task_spread": "0.100",
                             "wording_spread": "0.050"}]},
         "floors": None}
    d.update(kw)
    return d


def refuses(fn, *a, **kw):
    try:
        fn(*a, **kw)
    except stats.StatsError:
        return True
    return False


def git_show(commit, path):
    got = subprocess.run(["git", "-C", str(REPO), "show", f"{commit}:{path}"], capture_output=True)
    if got.returncode != 0:
        raise AssertionError(f"git show {commit[:8]}:{path} failed (a shallow clone or no git?): "
                             f"{got.stderr.decode(errors='replace').strip()}. This test needs the history; it never skips.")
    return got.stdout


