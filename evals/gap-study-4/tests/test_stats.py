class Table1Bounds(unittest.TestCase):
    def row(self, rows, **want):
        got = [r for r in rows if all(r[k] == v for k, v in want.items())]
        self.assertEqual(len(got), 1, want)
        return got[0]

    def test_counts_and_bounds_per_view(self):
        words = ["right"] * 6 + ["wrong"] * 2 + ["stop"] * 1 + ["harness-error"]
        recs = cell(words, "right")
        rows = stats.bounds_table(recs, design())
        trap = self.row(rows, task="t1", model="m1", harness=HX, half="trap")
        self.assertEqual(trap["harness_error"], 1)
        self.assertEqual(trap["failures"], {"right": 6, "n": 9, "lower": stats.bound(6, 9)[0],
                                            "upper": stats.bound(6, 9)[1]})
        self.assertEqual(trap["excluded"], {"right": 6, "n": 8, "lower": stats.bound(6, 8)[0],
                                            "upper": stats.bound(6, 8)[1], "out": 1})
        self.assertEqual(trap["raw"], {"right": 6, "wrong": 2, "stop": 1, "n": 9,
                                       "lower": stats.bound(6, 9)[0], "upper": stats.bound(6, 9)[1]})
        normal = self.row(rows, task="t1", model="m1", harness=HX, half="normal")
        self.assertEqual(normal["failures"]["right"], 10)
        self.assertEqual(normal["failures"]["n"], 10)
        self.assertEqual(normal["failures"]["upper"], "1.000")

    def test_bounds_rounded_outward_on_the_grid(self):
        self.assertEqual(stats.bound(10, 10), ("0.691", "1.000"))
        self.assertEqual(stats.bound(0, 10), ("0.000", "0.309"))
        lo, hi = stats.intervals.clopper_pearson(5, 10)
        self.assertEqual(stats.bound(5, 10), (stats.intervals.fmt(lo), stats.intervals.fmt(hi)))

    def test_harness_error_leaves_the_denominator(self):
        recs = cell(["harness-error"] * 2 + ["right"] * 8, "right")
        trap = self.row(stats.bounds_table(recs, design()), task="t1", model="m1", half="trap")
        self.assertEqual(trap["failures"]["n"], 8)
        # mutant: harness-error kept in the denominator (a record without standing reads wrong, fail-closed)
        with mock.patch.object(stats, "LEAVES_DENOMINATOR", ()):
            trap = self.row(stats.bounds_table(recs, design()), task="t1", model="m1", half="trap")
            self.assertEqual(trap["failures"]["n"], 10)

    def test_aborted_counts_against(self):
        recs = cell(["aborted"] + ["right"] * 9, "right")
        trap = self.row(stats.bounds_table(recs, design()), task="t1", model="m1", half="trap")
        self.assertEqual((trap["failures"]["right"], trap["failures"]["n"]), (9, 10))
        self.assertEqual(trap["excluded"]["out"], 1)

    def test_a_cell_with_no_graded_record_is_no_takes(self):
        recs = cell("harness-error", "right")
        rows = stats.bounds_table(recs, design())
        trap = self.row(rows, task="t1", model="m1", half="trap")
        self.assertEqual(trap["failures"], stats.NO_TAKES)
        # a design cell no record reached is a row too, printed as no takes, never as zero
        other = self.row(rows, task="t2", model="m2", half="normal")
        self.assertEqual(other["failures"], stats.NO_TAKES)
        self.assertEqual(stats.NO_TAKES, "no takes")
        text = stats.render_bounds(rows)
        self.assertIn("no takes", text)
        self.assertNotIn("0 of 0", text)

    def test_cells_keep_harnesses_apart(self):
        # one model name under two harnesses, same arm: two cells, never one
        recs = cell("right", "right", model="m1", harness=HX) + cell("wrong", "wrong", model="m1", harness=HY)
        d = design(harness_models={HX: ["m1"], HY: ["m1"]}, stronger_weaker={}, cross_vendor=[])

        def counts(rows, harness):
            got = [r["failures"] for r in rows if r["harness"] == harness and r["task"] == "t1"
                   and r["half"] == "trap" and r["model"] == "m1"]
            return got

        rows = stats.bounds_table(recs, d)
        self.assertEqual([(c["right"], c["n"]) for c in counts(rows, HX)], [(10, 10)])
        self.assertEqual([(c["right"], c["n"]) for c in counts(rows, HY)], [(0, 10)])
        # mutant: a cell key without the harness counts the two harnesses as one cell
        with mock.patch.object(stats, "half_cell_key",
                               lambda r: (r["arm"], r["task"], r["half"], r["model"], "one-harness")):
            rows = stats.bounds_table(recs, d)
            self.assertNotEqual([(c["right"], c["n"]) for c in counts(rows, HX) if c != stats.NO_TAKES], [(10, 10)])

    def test_no_records_is_no_takes_for_the_table(self):
        self.assertEqual(stats.bounds_table([], design()), stats.NO_TAKES)
        self.assertEqual(stats.render_bounds(stats.NO_TAKES).strip().splitlines()[-1], "no takes")


