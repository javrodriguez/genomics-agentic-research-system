class TheDriftTest(unittest.TestCase):
    """stats' bounds beside lane E1's original, read from git into a temporary module, on every (x, n), n <= 20."""

    def original(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "intervals_original.py"
            path.write_bytes(git_show(SHARED_COMMIT, ORIGINAL))
            spec = importlib.util.spec_from_file_location("intervals_original_68ec902f", path)
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)
            return mod

    def disagreements(self, orig):
        bad = []
        for n in range(1, 21):
            for x in range(n + 1):
                lo, hi = orig.clopper_pearson(x, n)
                if stats.bound(x, n) != (orig.fmt(lo), orig.fmt(hi)):
                    bad.append((x, n))
        return bad

    def test_bounds_agree_exactly(self):
        orig = self.original()
        self.assertNotEqual(Path(orig.__file__).resolve().parent, HERE)
        self.assertEqual(self.disagreements(orig), [])

    def test_a_drifted_bound_goes_red(self):
        orig = self.original()
        real = stats.intervals.clopper_pearson

        def drifted(x, n, alpha=stats.intervals.ALPHA):
            lo, hi = real(x, n, alpha)
            return lo, min(Fraction(1), hi + Fraction(1, 1000)) if x < n else hi

        with mock.patch.object(stats.intervals, "clopper_pearson", drifted):
            self.assertNotEqual(self.disagreements(orig), [])

    def test_e1_sizing_claim_rederived(self):
        # plan line 215: lane E1's sizing resolves only a 0.70 difference per cell before correction
        self.assertEqual(stats.intervals.smallest_detectable(10), 35)
        self.assertEqual(Fraction(2 * stats.intervals.smallest_detectable(10), 100), Fraction(70, 100))


class TheRecordIsClosed(unittest.TestCase):
    def test_a_sound_record_passes(self):
        for word in ("right", "wrong", "stop", "aborted", "harness-error"):
            stats.validate_record(outcome(word))
        stats.validate_record(rec(repeat=None, pressure=True))

    def test_without_agent_refused(self):
        bad = rec()
        del bad["agent"]
        self.assertTrue(refuses(stats.validate_record, bad))
        # mutant: a field list without agent and no agent check lets the record through
        with mock.patch.object(stats, "TAKE_FIELDS", tuple(f for f in stats.TAKE_FIELDS if f != "agent")), \
                mock.patch.object(stats, "_check_agent", lambda a: None):
            self.assertFalse(refuses(stats.validate_record, bad))

    def test_agent_never_defaulted(self):
        for bad_agent in (None, {}, {"harness": HX}, {"harness": "", "version": "1"},
                          {"harness": HX, "version": 3}, {"harness": HX, "version": "1", "extra": "x"}):
            self.assertTrue(refuses(stats.validate_record, rec(agent=bad_agent)), bad_agent)
        with mock.patch.object(stats, "AGENT_FIELDS", ("harness",)):
            self.assertFalse(refuses(stats.validate_record, rec(agent={"harness": HX})))

    def test_unknown_missing_mistyped_refused(self):
        self.assertTrue(refuses(stats.validate_record, dict(rec(), extra=1)))
        missing = rec()
        del missing["wording"]
        self.assertTrue(refuses(stats.validate_record, missing))
        for kw in ({"half": "positive"}, {"repeat": "1"}, {"repeat": True}, {"pressure": 1, "repeat": None},
                   {"repeat": None, "pressure": None}, {"repeat": 1, "pressure": False}, {"task": ""},
                   {"model": 5}, {"cell_state": "incomplete"}, {"views": {"failures": "right"}},
                   {"views": {"failures": "right", "excluded": "right", "raw": "maybe"}}, ["not", "a", "dict"]):
            bad = kw if isinstance(kw, list) else rec(**kw)
            self.assertTrue(refuses(stats.validate_record, bad), kw)
        self.assertFalse(refuses(stats.validate_record, rec(cell_state=stats.labels4.INCOMPLETE_MECHANICAL)))

    def test_exactly_one_of_repeat_and_pressure(self):
        self.assertTrue(refuses(stats.validate_record, rec(repeat=None, pressure=None)))
        self.assertTrue(refuses(stats.validate_record, rec(repeat=2, pressure=True)))
        with mock.patch.object(stats, "_one_level", lambda r: True):
            self.assertFalse(refuses(stats.validate_record, rec(repeat=2, pressure=True)))

    def test_rehearsal_and_pause_never_reach_results(self):
        for route in (stats.labels4.REHEARSAL, stats.labels4.PAUSE):
            self.assertTrue(refuses(stats.validate_record, rec(route=route)))
        with mock.patch.object(stats, "NEVER_IN_RESULTS", ()):
            self.assertFalse(refuses(stats.validate_record, rec(route=stats.labels4.PAUSE)))
        self.assertTrue(refuses(stats.validate_record, rec(route="ok")))

    def test_views_follow_the_label(self):
        # a stop is wrong / out / stop; a non-stop is right or wrong alike in all three
        self.assertTrue(refuses(stats.validate_record, rec(label="did-not-reach", views=dict(VIEWS_RIGHT))))
        self.assertTrue(refuses(stats.validate_record, rec(label="right-move", views=dict(VIEWS_STOP))))
        self.assertTrue(refuses(stats.validate_record, rec(views={"failures": "right", "excluded": "wrong",
                                                                  "raw": "right"})))
        with mock.patch.object(stats, "STOP_LABELS", ()):
            self.assertFalse(refuses(stats.validate_record, rec(label="did-not-reach", views=dict(VIEWS_RIGHT))))

    def test_route_and_label_agree(self):
        self.assertTrue(refuses(stats.validate_record, rec(route="aborted", label="right-move")))
        self.assertTrue(refuses(stats.validate_record, rec(route="harness-error", label="right-move")))
        self.assertTrue(refuses(stats.validate_record, rec(route="harness-error", label="harness-error")))
        self.assertTrue(refuses(stats.validate_record, rec(route="graded", label="harness-error", views=None)))

    def test_flagged_then_acted_is_unused_in_round_4(self):
        self.assertTrue(refuses(stats.validate_record, rec(label=stats.labels4.FLAGGED_THEN_ACTED,
                                                           views=dict(VIEWS_WRONG))))
        with mock.patch.object(stats, "UNUSED_LABELS", ()):
            self.assertFalse(refuses(stats.validate_record, rec(label=stats.labels4.FLAGGED_THEN_ACTED,
                                                                views=dict(VIEWS_WRONG))))


