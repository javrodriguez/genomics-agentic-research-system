# regex-only constants (never read by name from the environment here): the written rule
RISKY = re.compile(r"(AUTH|TOKEN|KEY|CREDENTIAL|BILLING|URL|URI|ENDPOINT|PROXY|PROJECT|LOCATION|REGION|ACCOUNT|VERTEX|"
                   r"SANDBOX|MODEL|HEADER|CERTIFICATE|MTLS|GRANT|TELEMETRY|STORAGE|EXTERNAL|SETTINGS|PATH|DIR|FILE|"
                   r"SCOPE|CLIENT|TENANT|AUDIENCE|EMAIL|IMPERSONAT|EXECUTABLE|ALIAS|EXP|CONFIG|METADATA|"
                   r"SECRET|PASS|HOST|PORT|ROUTING|API_DEFAULT)")   # the review's NIT 5 added the last six
REFUSE = ("credential", "route", "ambiguous")
rows, unplaced = [], []
for n, e in sorted(d["names"].items()):
    read = sorted(set(e["kinds"]) - {"vendor-regex"})
    if n in T:
        cls, why = T[n], "table"
    elif read:
        unplaced.append(n)
        continue
    else:
        cls = "ambiguous" if RISKY.search(n) else "harmless"
        why = "regex-only rule: " + ("a risky word" if cls == "ambiguous" else "a constant with no risky word")
    rows.append({"name": n, "class": cls, "read_as": read or ["vendor-regex only"], "why": why})
if unplaced:
    sys.exit("unplaced names the CLI reads from the environment: " + ", ".join(unplaced))
refuse = sorted(r["name"] for r in rows if r["class"] in REFUSE)
print(json.dumps({"sweep": SWEEP.rsplit("/", 1)[-1], "sweep_sha256": hashlib.sha256(raw).hexdigest(),
                  "package_version": d["package_version"], "package_text_digest": d["package_text_digest"],
                  "names": len(rows), "rows": rows, "refuse_if_present": refuse,
                  "counts": {c: sum(1 for r in rows if r["class"] == c) for c in
                             ("row", "own-login", "credential", "route", "ambiguous", "harmless")}},
                 indent=1, sort_keys=True))
